self.addEventListener('install', (e) => {
  self.skipWaiting();
  e.waitUntil(caches.open(CACHE).then((c) => Promise.all(SHELL.map((u) => c.add(u).catch(() => {})))));
});
self.addEventListener('activate', (e) => {
  e.waitUntil(caches.keys().then((keys) => Promise.all(keys.filter((k) => k !== CACHE && k !== AUDIO_CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  // Navigation -> serve cached index (offline fallback).
  if (req.mode === 'navigate') {
    e.respondWith(fetch(req).catch(() => caches.match('./index.html')));
    return;
  }
  // Music files -> cache-first against the persistent audio bucket. On miss just pass through
  // (don't cache here: media elements send Range → 206, which is not the full file; the app's
  // prefetchAudio() stores full 200 responses in AUDIO_CACHE for offline).
  if (isAudio(url)) {
    e.respondWith(caches.open(AUDIO_CACHE).then((c) => c.match(req).then((hit) => hit || fetch(req))));
    return;
  }
  // tracks.json -> network-first (fresh playlist), fall back to the audio cache offline.
  if (url.pathname.endsWith('/audio/tracks.json') || url.pathname.endsWith('audio/tracks.json')) {
    e.respondWith(fetch(req).then((res) => { const copy = res.clone(); caches.open(AUDIO_CACHE).then((c) => c.put(req, copy)).catch(() => {}); return res; }).catch(() => caches.open(AUDIO_CACHE).then((c) => c.match(req))));
    return;
  }
  // Cache-first with runtime caching (JS modules carry ?v=N so new deploys fetch fresh).
  e.respondWith(caches.match(req).then((hit) => hit || fetch(req).then((res) => {
    const copy = res.clone();
    caches.open(CACHE).then((c) => c.put(req, copy)).catch(() => {});
    return res;
  }).catch(() => hit)));
});
